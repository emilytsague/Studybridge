import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,cp,readFile,writeFile,readdir,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {scrypt} from 'node:crypto';
test('maintenance backs up, restores without overwrite and resets only the chosen account',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'studybridge-maintenance-'));
 t.after(async()=>{assert(path.resolve(root).startsWith(path.resolve(os.tmpdir())+path.sep));assert(path.basename(root).startsWith('studybridge-maintenance-'));await rm(root,{recursive:true,force:true})});
 await mkdir(path.join(root,'scripts'));await mkdir(path.join(root,'data'));
 await cp(new URL('../scripts/maintenance.mjs',import.meta.url),path.join(root,'scripts','maintenance.mjs'));
 const users=[{id:'alice-id',username:'alice',salt:'old',hash:'old'},{id:'bob-id',username:'bob',salt:'bob',hash:'bob-hash'}];
 await writeFile(path.join(root,'data','users.json'),JSON.stringify(users));
 await writeFile(path.join(root,'data','sessions.json'),JSON.stringify([['alice-token',{userId:'alice-id'}],['bob-token',{userId:'bob-id'}]]));
 await writeFile(path.join(root,'data','document.txt'),'Synthetic course');
 const probe=net.createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));const port=probe.address().port;await new Promise(r=>probe.close(r));
 const run=(...args)=>promisify(execFile)(process.execPath,[path.join(root,'scripts','maintenance.mjs'),...args],{cwd:root,env:{...process.env,DATA_DIR:path.join(root,'data'),PORT:String(port)}});
 await run('backup');const [snapshot]=await readdir(path.join(root,'backups'));
 const backup=path.join(root,'backups',snapshot);assert.equal(await readFile(path.join(backup,'data','document.txt'),'utf8'),'Synthetic course');
 await run('restore',backup);const restored=(await readdir(root)).find(n=>n.startsWith('data-restored-'));
 assert.equal(await readFile(path.join(root,restored,'document.txt'),'utf8'),'Synthetic course');assert.equal(await readFile(path.join(root,restored,'sessions.json'),'utf8'),'[]');
 assert.deepEqual(JSON.parse(await readFile(path.join(root,'data','users.json'),'utf8')),users);
 const reset=await run('reset-password','alice');const password=reset.stdout.match(/alice : ([\w-]+)/)[1];
 const updated=JSON.parse(await readFile(path.join(root,'data','users.json'),'utf8'));
 assert.deepEqual(updated[1],users[1]);assert.equal((await promisify(scrypt)(password,updated[0].salt,64)).toString('hex'),updated[0].hash);
 assert.equal(JSON.parse(await readFile(path.join(root,'data','sessions.json'),'utf8')).length,1);
});
